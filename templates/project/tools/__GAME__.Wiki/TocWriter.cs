using System.Text;

namespace __GAME__.Wiki;

/// <summary>
/// Writes DocFX <c>toc.yml</c> files: the reference section from the generated pages, and the design docs section
/// from the Markdown files in <c>docs/</c>, so neither needs a hand-kept list.
/// </summary>
internal static class TocWriter
{
    private const string Header = "# Generated by tools/__GAME__.Wiki. Do not edit.\n";

    /// <summary>The prefix the docs' first headings carry, left out of navigation titles.</summary>
    private const string TitlePrefix = "__TITLE__ — ";

    /// <summary>The docs that lead the design docs section, in this order; any others follow by name.</summary>
    private static readonly string[] LeadingDocs =
    [
        "GDD.md",
        "ART_DIRECTION.md",
        "AUDIO.md",
        "CODING_STANDARDS.md",
        "IMPLEMENTATION_PLAN.md",
    ];

    /// <summary>
    /// Writes the TOC of the generated pages, grouping consecutive pages that share a group.
    /// </summary>
    /// <param name="pages">The pages, in navigation order.</param>
    /// <returns>The YAML.</returns>
    public static string Pages(IReadOnlyList<GeneratedPage> pages)
    {
        var yaml = new StringBuilder(Header);
        string? group = null;
        foreach (GeneratedPage page in pages)
        {
            if (page.Group != group)
            {
                group = page.Group;
                if (group is not null)
                {
                    yaml.Append("- name: ").Append(Quote(group)).Append("\n  items:\n");
                }
            }

            AppendItem(yaml, group is null ? string.Empty : "    ", page.Title, page.Path);
        }

        return yaml.ToString();
    }

    /// <summary>
    /// Writes the TOC of <c>docs/</c>: the top-level docs, then the ADR index with every ADR under it. Titles are the
    /// files' first headings, without the game's name prefix.
    /// </summary>
    /// <param name="docsDirectory">The <c>docs/</c> folder.</param>
    /// <param name="tocDirectory">
    /// The folder the TOC is written to. DocFX resolves TOC links from the TOC's own source location, so entries point
    /// at the files where they are, relative to it.
    /// </param>
    /// <returns>The YAML.</returns>
    public static string Docs(string docsDirectory, string tocDirectory)
    {
        var yaml = new StringBuilder(Header);
        string prefix = Path.GetRelativePath(tocDirectory, docsDirectory).Replace('\\', '/') + "/";
        IEnumerable<string> docs = Directory
            .GetFiles(docsDirectory, "*.md")
            .Select(Path.GetFileName)
            .OfType<string>()
            .OrderBy(name => Array.IndexOf(LeadingDocs, name) is var lead and >= 0 ? lead : LeadingDocs.Length)
            .ThenBy(name => name, StringComparer.Ordinal);
        foreach (string name in docs)
        {
            AppendItem(yaml, string.Empty, Title(Path.Combine(docsDirectory, name)), prefix + name);
        }

        string adrDirectory = Path.Combine(docsDirectory, "adr");
        if (Directory.Exists(adrDirectory))
        {
            AppendItem(yaml, string.Empty, "Architecture decisions", prefix + "adr/README.md");
            yaml.Append("  items:\n");
            foreach (
                string path in Directory
                    .GetFiles(adrDirectory, "*.md")
                    .Where(path => Path.GetFileName(path) != "README.md")
                    .Order(StringComparer.Ordinal)
            )
            {
                AppendItem(yaml, "    ", Title(path), prefix + "adr/" + Path.GetFileName(path));
            }
        }

        return yaml.ToString();
    }

    /// <summary>
    /// Appends one TOC entry.
    /// </summary>
    /// <param name="yaml">The YAML so far.</param>
    /// <param name="indent">The indent of the entry.</param>
    /// <param name="name">The navigation name.</param>
    /// <param name="href">The page path.</param>
    private static void AppendItem(StringBuilder yaml, string indent, string name, string href)
    {
        yaml.Append(indent).Append("- name: ").Append(Quote(name)).Append('\n');
        yaml.Append(indent).Append("  href: ").Append(Quote(href)).Append('\n');
    }

    /// <summary>
    /// Reads a Markdown file's first level-1 heading.
    /// </summary>
    /// <param name="path">The file.</param>
    /// <returns>The heading text, or the file name when there is none.</returns>
    private static string Title(string path)
    {
        string? heading = File.ReadLines(path).FirstOrDefault(line => line.StartsWith("# ", StringComparison.Ordinal));
        string title = heading?[2..].Trim() ?? Path.GetFileNameWithoutExtension(path);
        return title.StartsWith(TitlePrefix, StringComparison.Ordinal) ? title[TitlePrefix.Length..] : title;
    }

    /// <summary>
    /// Quotes a YAML scalar.
    /// </summary>
    /// <param name="text">The text.</param>
    /// <returns>The double-quoted scalar.</returns>
    private static string Quote(string text) =>
        "\""
        + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)
        + "\"";
}
